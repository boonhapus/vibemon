	/** Merge each row's '#' cells into horizontal run rects. */
	function rects(name: PixelIconName): { x: number; y: number; w: number }[] {
		const out: { x: number; y: number; w: number }[] = [];
		GLYPHS[name].forEach((row, y) => {
			let x = -1;
			for (let i = 0; i <= row.length; i++) {
				if (row[i] === '#' && x === -1) x = i;
				if (row[i] !== '#' && x !== -1) {
					out.push({ x, y, w: i - x });
					x = -1;
				}
			}
		});
		return out;
	}
